//! Stages the release binaries and embeds them into the installer.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    // crates/spass-installer -> compiler -> target/release
    let release = manifest
        .join("..")
        .join("..")
        .join("target")
        .join("release");
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let staged = out_dir.join("payload");
    fs::create_dir_all(&staged).expect("create payload dir");

    // The bootstrap source is the self-hosted numeric core.
    // It lives outside the compiler tree.
    let repo = manifest.join("..").join("..").join("..");
    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    let exe = release.join("spass.exe");
    if !exe.exists() {
        panic!(
            "spass.exe not found at {}.\n\
             Build the compiler in release mode first:\n\
             \x20   cargo build --release -p spass\n\
             or just run:  .\\package.ps1",
            exe.display()
        );
    }
    entries.push(("SPASS_EXE".to_string(), exe));

    // The C runtime travels as source inside each generated module, so
    // there is no runtime library to ship. The unwinder below is the
    // only DLL the compiler binary needs.
    let bootstrap = repo.join("examples").join("bootstrap").join("src").join("bootstrap.spass");
    if bootstrap.exists() {
        entries.push(("SPASS_BOOTSTRAP".to_string(), bootstrap));
    }

    // A Spass binary built for the Rust `x86_64-pc-windows-gnullvm` target
    // imports `libunwind.dll`. It ships inside the toolchain and is not on
    // PATH for a machine that only has Spass, so an install without it
    // produces a `spass.exe` that dies before `main` with
    // STATUS_DLL_NOT_FOUND (0xC0000135) and prints nothing. Embed it so
    // the installed toolchain is self-contained.
    if let Some(unwind) = find_libunwind() {
        entries.push(("SPASS_LIBUNWIND".to_string(), unwind));
    } else {
        println!(
            "cargo:warning=libunwind.dll not found; the installed spass.exe may fail \
             to start with STATUS_DLL_NOT_FOUND unless the Rust toolchain bin \
             directory is on PATH"
        );
    }

    // Copy each payload into OUT_DIR so the generated `include_bytes!`
    // paths are stable regardless of the source location.
    for (_name, src) in &entries {
        let dest = staged.join(src.file_name().expect("file name"));
        fs::copy(src, &dest)
            .unwrap_or_else(|e| panic!("stage {}: {}", src.display(), e));
        println!("cargo:rerun-if-changed={}", src.display());
    }

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs - do not edit.\n");
    generated.push_str(&format!(
        "pub static SPASS_EXE: &[u8] = include_bytes!(r\"{}\");\n",
        staged.join("spass.exe").display()
    ));
    // The optional payloads are always declared so the binary compiles
    // whether or not the release build produced them.
    for (name, file) in [
        ("SPASS_BOOTSTRAP", "bootstrap.spass"),
        ("SPASS_LIBUNWIND", "libunwind.dll"),
    ] {
        let p = staged.join(file);
        if p.exists() {
            generated.push_str(&format!(
                "pub static {}: Option<&[u8]> = Some(include_bytes!(r\"{}\"));\n",
                name,
                p.display()
            ));
        } else {
            generated.push_str(&format!(
                "pub static {}: Option<&[u8]> = None;\n",
                name
            ));
        }
    }
    println!("cargo:rerun-if-changed=build.rs");

    let rs = out_dir.join("payload.rs");
    fs::write(&rs, generated).expect("write payload.rs");
    let _ = Path::new(&rs);
}

/// Locate the `libunwind.dll` that the host toolchain links against.
///
/// It lives under `<toolchain>/lib/rustlib/<triple>/bin/`. We search every
/// installed toolchain and take the most recently written match, which is
/// the one the current build is most likely linked against. Returns `None`
/// when the host target does not need it (e.g. a `*-pc-windows-msvc` host,
/// where unwinding goes through the OS).
fn find_libunwind() -> Option<PathBuf> {
    let home = env::var_os("RUSTUP_HOME")
        .map(PathBuf::from)
        .or_else(|| env::var_os("USERPROFILE").map(|p| PathBuf::from(p).join(".rustup")))?;

    let mut best: Option<(std::time::SystemTime, PathBuf)> = None;
    let mut stack = vec![home.join("toolchains")];
    while let Some(dir) = stack.pop() {
        let Ok(rd) = fs::read_dir(&dir) else { continue };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                stack.push(p);
                continue;
            }
            if p.file_name().and_then(|n| n.to_str()) != Some("libunwind.dll") {
                continue;
            }
            // Only the toolchain's own bin dir counts, not build artifacts.
            if !p.to_string_lossy().contains("rustlib") {
                continue;
            }
            let mtime = e
                .metadata()
                .and_then(|m| m.modified())
                .unwrap_or(std::time::UNIX_EPOCH);
            if best.as_ref().map(|(t, _)| mtime > *t).unwrap_or(true) {
                best = Some((mtime, p));
            }
        }
    }
    best.map(|(_, p)| p)
}
