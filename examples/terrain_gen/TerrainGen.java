import java.io.*;
import java.net.*;
import java.util.*;

/**
 * Terrain generator renderer (section 1.6).
 *
 * Spass (examples/terrain_gen) generates a 16x16 tile map as a resident
 * world: heights (layered sines), tile classification (water/sand/grass/
 * mountain) and progress all live in Spass. This front end acknowledges
 * each tile and renders the map.
 *
 * Usage: java TerrainGen <projectDir> <port>
 */
public class TerrainGen {
    static String host = "127.0.0.1";
    static int port = 9100;
    static String project;

    static Socket sock;
    static DataOutputStream out;
    static DataInputStream in;

    static void ensureConn() throws IOException {
        if (sock != null && sock.isConnected() && !sock.isClosed()) return;
        sock = new Socket();
        sock.connect(new InetSocketAddress(host, port), 2000);
        out = new DataOutputStream(new BufferedOutputStream(sock.getOutputStream()));
        in = new DataInputStream(new BufferedInputStream(sock.getInputStream()));
    }

    static void closeConn() {
        try { if (sock != null) sock.close(); } catch (IOException ignored) {}
        sock = null;
    }

    static String rpc(String json) throws IOException {
        IOException last = null;
        for (int attempt = 0; attempt < 3; attempt++) {
            try {
                ensureConn();
                byte[] body = json.getBytes("UTF-8");
                out.writeInt(body.length);
                out.write(body);
                out.flush();
                int len = in.readInt();
                byte[] resp = new byte[len];
                in.readFully(resp);
                return new String(resp, "UTF-8");
            } catch (IOException e) {
                closeConn();
                last = e;
            }
        }
        throw last;
    }

    static double num(String json, String field) {
        String key = "\"" + field + "\":";
        int i = json.indexOf(key);
        if (i < 0) throw new RuntimeException("field missing: " + field + " in " + json);
        i += key.length();
        int j = i;
        while (j < json.length() &&
               (Character.isDigit(json.charAt(j)) || "-+.eE".indexOf(json.charAt(j)) >= 0)) j++;
        return Double.parseDouble(json.substring(i, j));
    }

    static void setSocket(String channel, double value) throws IOException {
        rpc("{\"cmd\":\"set\",\"project\":\"" + project + "\",\"channel\":\"" + channel
            + "\",\"value\":" + value + ",\"mode\":\"socket\"}");
    }

    static Double get(String channel) throws IOException {
        String r = rpc("{\"cmd\":\"get\",\"project\":\"" + project + "\",\"channel\":\""
                       + channel + "\"}");
        if (!r.contains("\"found\":true")) return null;
        return num(r, "value");
    }

    static void startWorld() throws IOException {
        String r = rpc("{\"cmd\":\"start\",\"project\":\"" + project + "\"}");
        if (!r.contains("\"ok\":true")) throw new RuntimeException("start failed: " + r);
        File outDir = new File(project, "data/output");
        File[] stale = outDir.listFiles();
        if (stale != null) for (File f : stale) f.delete();
    }

    static char tileChar(double code) {
        // 0=water 1=sand 2=grass 3=mountain
        switch ((int) Math.round(code)) {
            case 0: return '~';
            case 1: return '.';
            case 2: return '#';
            default: return '^';
        }
    }

    public static void main(String[] args) throws Exception {
        project = new File(args[0]).getCanonicalPath().replace('\\', '/');
        port = Integer.parseInt(args[1]);

        startWorld();
        double[] heights = new double[256];
        int last = -1;

        // Consume 256 tiles: the world publishes (idx, h) then waits for
        // our ack — we ack with the index we consumed.
        for (int ack = 0; ack < 256; ack++) {
            double idx;
            int polls = 0;
            while (true) {
                Double i = get("tile_idx");
                if (i != null && (int) Math.round(i) == ack) { idx = i; break; }
                if (++polls > 100) throw new RuntimeException(
                    "no tile " + ack + " from the world (last=" + i + ")");
                Thread.sleep(25);
            }
            heights[ack] = get("tile_h");
            setSocket("ack", ack);
            last = ack;
        }
        // Wait for the generator to report completion.
        for (int i = 0; i < 100; i++) {
            Double done = get("gen_done");
            if (done != null && done >= 255.5) break;
            Thread.sleep(25);
        }

        System.out.println("terrain generated by Spass: " + (last + 1) + " tiles (16x16)");
        System.out.println("legend: ~ water  . sand  # grass  ^ mountain");
        System.out.println("+----------------+");
        for (int z = 0; z < 16; z++) {
            StringBuilder row = new StringBuilder("|");
            for (int x = 0; x < 16; x++) {
                row.append(tileChar(heights[z * 16 + x]));
            }
            row.append('|');
            System.out.println(row);
        }
        System.out.println("+----------------+");

        closeConn();
    }
}
